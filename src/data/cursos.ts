// Deriva intro/decision/checklist sin reescribir las 30 lecciones
export function getIntro(l: Leccion): { parrafos: string[]; tips: string[] } {
  if (l.intro) return l.intro;
  return {
    parrafos: [
      `En esta lección verás: ${l.concepto}`,
      `Tu objetivo: ${l.mision}`,
      "Usarás solo bloques de tu lenguaje. Al final publicarás tu página con su URL.",
    ],
    tips: ["Lee cada paso en orden", "En el Lab tú decides qué tendrá la página", "El Boss exige 1 imagen o video tuyo"],
  };
}

export function getLabDecision(l: Leccion): string {
  return l.labDecision || "Tú decides qué tendrá esta página. Elige tu tema (juego, música, tienda, blog) y constrúyelo con bloques + tus archivos.";
}

export function getBossChecklist(l: Leccion): string[] {
  if (l.bossChecklist) return l.bossChecklist;
  if (l.curso === "html") return ["2+ bloques", "1 imagen o video tuyo", "Quiz 100%", "Publicar URL"];
  if (l.curso === "css") return ["1 bloque de HTML + 1 bloque de CSS", "1 imagen o video tuyo", "Se ve bien en móvil", "Publicar URL"];
  return ["Lógica funcionando", "1 imagen o video tuyo", "Quiz 100%", "Publicar URL"];
}

